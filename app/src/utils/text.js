// ================================================================
// 文本小工具（utils/text.js）
// 职责：把**给人看的散文**落成**纯文本**（去 Markdown 记号）
// 依赖：无（叶子模块，**不依赖 DOM** —— 所以 core / ui / features 都能用）
// ================================================================

/**
 * 去 Markdown 记号（`**强调**` 与 `` `命令` ``），**不改字**。
 *
 * 为什么必须过这一道：构建侧写的散文（报告里的 `why` / `action`、各种提示文案）是
 * **写给开发者看的**，带强调记号；而界面把它们当**纯文本**念 —— 不过这一道，
 * 页面上就会原样漏出星号和反引号（实测漏过好几次）。
 *
 * ⚠️ **凡是"人看得见的字"都要过它**，不只是 `textContent` / `innerHTML`：
 *    **`title`（鼠标悬停提示）同样是给人看的** —— 以前只在 `textContent` 上做了，
 *    `title` 漏了一大片（用户 2026-10-06 看到悬停里一串星号）。
 *
 * ⚠️ **只有这一份实现**：`core/coverage.js` 的 `plainProse` 与 `ui/kit/report.js` 的
 *    `plain` 都从这里再导出（以前是两份一模一样的代码 + 两个名字）。
 */
export function plainProse(text) {
    return String(text === undefined || text === null ? '' : text)
        .replace(/\*\*/g, '')
        .replace(/\\?`/g, '');
}

/** 同一个东西的短名字（模板与各页面的调用点多半写 `plain(...)`） */
export const plain = plainProse;
