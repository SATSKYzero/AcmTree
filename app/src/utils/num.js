// ================================================================
// 数字小工具（utils/num.js）
// 职责：把**给人看的数字**落成字符串（强度 / 题数 / 目标那种量）
// 依赖：无（叶子模块，core / ui / features 都能用）
// ================================================================

/**
 * 最多一位小数、不留 `.0`（`2` / `2.5` / `0.3`）。
 *
 * 为什么必须只有一份：它是"**屏幕上那个数字长什么样**"的规则 —— 计划栏、计划页、
 * 计划页各块、两张图都要显示强度/题数，各写一份必然分叉（一处 `2`、一处 `2.0`、一处 `2.00`）。
 * 实测（2026-10-13）：这条一行式子曾在 `ui/plan/` 下**抄了四份**（`planBar` / `planPage` /
 * `planBlocks` / `planCharts`），收敛到这儿；守卫在 `src/test/docAnchors.test.js` 的
 * 「唯一实现」名单（`fmtAmount` + 这条式子的字面量各只许一处）。
 *
 * ⚠️ 与 `core/coverage.js:fmtNum`（**千分位** `24,528`）不是一回事，别混用；
 *    也不是 `Number.toFixed`（那个会留下没意义的零）。
 * ⚠️ **算不出来的值（`null` / `undefined`）会得到 `NaN`** —— 这是**故意的**：
 *    它是"这里没算出来"的信号，别在这函数里悄悄当 0。调用方要先判空
 *    （例：`planBlocks.js` 的「推荐训练强度」在 `leftDays === null` 时直接显示「—」，不走这里）。
 *
 * @param {*} v 数字（或能转成数字的东西）
 * @returns {string} `2` / `2.5` / `0.3`
 */
export function fmtAmount(v) {
    return (Math.round(Number(v) * 10) / 10).toString();
}

/**
 * **通过率**怎么显示：最多 3 位小数、不留尾零（`0.031` / `0.11` / `22.5` / `100`）。
 *
 * 为什么不复用 `fmtAmount`（一位小数）：通过率侧的控制点常常小到 **0.03%~0.2%**，
 * 一位小数会把 `0.11` 和 `0.03125` 都显示成 `0.1` / `0` —— 实测（2026-10-13）计划页那张表
 * 里两行看起来**一模一样**（用户当场会问"这两行是什么区别"）。所以通过率单独一份。
 *
 * @param {*} v 通过率（百分数，如 `22.5`）
 * @returns {string} `0.031` / `22.5`
 */
export function fmtPercent(v) {
    return (Math.round(Number(v) * 1000) / 1000).toString();
}
